"""Write data/decals.js for the decal page from decals.py's decals.json (and items.py's mushrooms.json, for links).

Usage (from the site's root folder): make_decal_data.py <decals.json> <mushrooms.json>
"""
import json, sys
decals = json.load(open(sys.argv[1], encoding='utf-8'))
ids = {m['name']: m['id'] for m in json.load(open(sys.argv[2], encoding='utf-8'))['mushrooms']}
out = []
for x in decals:
    y = {k: x[k] for k in ('id', 'no', 'name', 'desc', 'icon', 'category', 'rarity', 'source')}
    if x['premium']: y['premium'] = True
    if x['psOnly']: y['psOnly'] = True
    if x['sell']['coins'] or x['sell']['recycle']: y['sell'] = x['sell']
    if x['buy']['coins']: y['buy'] = x['buy']['coins']
    if 'unlock' in x: y['unlock'] = [dict(u, id=ids[u['mushroom']]) if u['mushroom'] in ids else u for u in x['unlock']]
    if 'stewOdds' in x: y['stewOdds'] = x['stewOdds']
    out.append(y)
open('data/decals.js', 'w', encoding='utf-8', newline='\n').write(
    "// Generated by tools/decals.py + make_decal_data.py from the game's masters.db (master_skill and related tables).\nwindow.DECALS = "
    + json.dumps(out, ensure_ascii=False, separators=(',', ':')).replace('},{', '},\n{') + ';\n')
print(len(out), 'decals,', sum(1 for y in out if y.get('psOnly')), 'PlayStation-only')
