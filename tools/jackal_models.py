"""Dump and pose the Jackals' meshes for the renderer and the 3D view.

Usage: jackal_models.py <dump-dir>
       jackal_models.py <dump-dir> --pack <shots-dir> <model3d-dir> <js-file>

The second form runs after render.html's renderJackals() and bakeJackalTextures() have saved into <shots-dir>: it packs
each posed mesh into <model3d-dir>/<name>.bin (pack3d.py's layout), copies the baked textures there once each (sections
that share identical images, such as the hair and its underside, point at one copy), and writes the layout to <js-file>.

The Jackals are whole-character meshes (body, armour and hair in one SkeletalMesh): CH_Enemy_JackalsX/Y/Z for the
standard and R tiers, and CH_Enemy_JackalsX002/Y002/Z002 for the red-and-black D tier. Each is posed with the
fighters' neutral idle (the Jackals share the fighter skeleton; Z uses the female set). Writes the meshes with
extract.py's functions, the posed vertices with pose.py's, and jackals.json (same shape as models.json, one entry
per mesh) into the dump directory.
"""
import os, sys, json, hashlib, shutil
from array import array

D = sys.argv[1]
if sys.argv[2:3] == ['--pack']:
    SHOTS, OUT, JS = sys.argv[3:6]
    os.makedirs(OUT, exist_ok=True)
    def load(name, kind, t):
        a = array(t); a.frombytes(open(os.path.join(D, '%s.%s.bin' % (name, kind)), 'rb').read()); return a
    seen = {}      # image hash -> texture name already copied

    def tex(name):
        """Copy model3d_<name>.webp into OUT under the first name with identical bytes; return that name."""
        data = open(os.path.join(SHOTS, 'model3d_%s.webp' % name), 'rb').read()
        h = hashlib.sha1(data).hexdigest()
        if h not in seen:
            seen[h] = name; open(os.path.join(OUT, name + '.webp'), 'wb').write(data)
        return seen[h]
    out = {}
    for m in json.load(open(os.path.join(D, 'jackals.json'))):
        b = m['body']; name = b['name']
        pos, nrm, uv, idx = load(name, 'pose.pos', 'f'), load(name, 'pose.nrm', 'f'), load(name, 'uv', 'f'), load(name, 'idx', 'I')
        nv = len(pos) // 3
        assert nv < 65536
        n8 = array('b')
        for i in range(nv):
            n8.extend(max(-127, min(127, round(nrm[3 * i + k] * 127))) for k in range(3)); n8.append(0)
        groups = []; tris = array('H')
        for g in b['groups']:
            mat = g['material']; tn = mat['name'][3:] if mat['name'].startswith('MI_') else mat['name']
            gi = dict(start=len(tris), count=g['count'])
            if mat['name'].endswith('_Glass'): gi['kind'] = 'glass'
            else:
                gi.update(d=tex(tn + '_D'), n=tex(tn + '_N'))
                if '_Hair' in (mat.get('parent') or ''): gi.update(kind='hair', a=tex(tn + '_A'))
            groups.append(gi); tris.extend(array('H', idx[g['start']:g['start'] + g['count']]))
        with open(os.path.join(OUT, name + '.bin'), 'wb') as f:
            for a in (pos, n8, uv, tris): a.tofile(f)
        out[m['id']] = dict(name=name, verts=nv, indices=len(tris), groups=groups, top=m['pose']['max'][1],
                            centre=[(m['pose']['min'][0] + m['pose']['max'][0]) / 2, (m['pose']['min'][2] + m['pose']['max'][2]) / 2])
    open(JS, 'w', newline='\n').write('// Generated by tools/jackal_models.py --pack: mesh layout for the Jackals page\'s 3D view (pack3d.py\'s .bin format;\n'
                                      '// each section names its colour (d), normal (n) and, for hair, opacity (a) images in model3d/).\nwindow.JACKALS3D = '
                                      + json.dumps(out, separators=(',', ':')).replace('},"JACKAL', '},\n"JACKAL') + ';\n')
    print(len(out), 'meshes,', len(seen), 'textures')
    sys.exit()

import extract, pose
pose.D = D
MESHES = [   # id, label, gender
    ('X', 'Jackal X', 'male'), ('Y', 'Jackal Y', 'male'), ('Z', 'Jackal Z', 'female'),
    ('X002', 'Jackal X (D)', 'male'), ('Y002', 'Jackal Y (D)', 'male'), ('Z002', 'Jackal Z (D)', 'female'),
]
anims = {}
models = []
for mid, label, gender in MESHES:
    body = extract.export_mesh('CH_Enemy_Jackals%s.Meshes.SK_CH_Enemy_Jackals%s' % (mid, mid))
    if gender not in anims: anims[gender] = pose.read_sequence(gender, 'ANI_CH_IDL_Neutral')
    bw, op = pose.pose_mesh(body, None, anims[gender])
    h = bw['HeadJT'][1]; ys = op[1::3]
    models.append(dict(id='JACKAL_' + mid, label=label, gender=gender, body=body, hair=None,
                       pose=dict(sequence='ANI_CH_IDL_Neutral', head=[h[0], -h[1], h[2]],
                                 min=[min(op[0::3]), min(ys), min(op[2::3])], max=[max(op[0::3]), max(ys), max(op[2::3])])))
    print(label, 'groups', [g['mat'] for g in body['groups']])
json.dump(models, open(os.path.join(D, 'jackals.json'), 'w'), indent=1)
print('done', len(models))
