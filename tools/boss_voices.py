"""Copy every voice clip of the Dons and mini bosses (Ogg Vorbis, as stored; nothing is re-encoded) and write data/bossvoices.js.

Usage (from the site's root folder): boss_voices.py
LID_MASTERS can point at an unmodded copy of the database, as for items.py.

The clips are spread over many localized packages (LOC_INT for English, LOC_JPN for Japanese): the Dons' own voice
packages, the bosses' animation packages and the boss stages. Every package is searched and each clip is taken once:
  SNW_VOX_CH_BB0<n>_*   Don n's combat voice (1 Max Sharp, 2 Colonel Jackson, 3 Mr. Crowley, 4 Taro Gunkanyama)
  SNW_VOX_CH_MB0<n>_*   mini boss n's voice (1 COEN, 2 JIN-DIE, 3 GOTO-9, 4 U-10)
  SNW_VOX_CH_4H_<x>_*   the 4 FORCEMEN's voices (W White Steel, R Red Napalm, B Black Thunder, P Pale Wind)
  SNW_VOX_BS_*          a Don's lines during the fight; text in master_text section BS_<scene>, id <speaker>_<nnnn>
  SNW_VOX_JS_*          a Don's arena scene before and after the fight, one clip per scene; text is the whole section
The speaker ids are MAXXX, JACKS, CROWL and GUNKA. Clips are written to voice/boss/<clip>_<en|jp>.ogg.
"""
import os, re, json, sqlite3, collections
import upk

OUT = os.path.join('voice', 'boss')
os.makedirs(OUT, exist_ok=True)
DB = os.path.abspath(os.environ.get('LID_MASTERS') or os.path.join(upk.GAME, '..', 'Content', 'masters.db')).replace(os.sep, '/')
c = sqlite3.connect('file:%s?mode=ro' % DB, uri=True)
TEXT = collections.defaultdict(list)       # (section, snd) -> [(id, text)]
for s, i, snd, t in c.execute("select sct, id, snd, txt from master_text where lang='int' and (sct like 'BS\\_%' escape '\\' or sct like 'JS\\_%' escape '\\') order by sct, id"):
    TEXT[(s, snd)].append((i, t))
SPEAKER = {'MAXXX': 'DON_MAX', 'JACKS': 'DON_JACKSON', 'CROWL': 'DON_CROWLEY', 'GUNKA': 'DON_GUNKANYAMA'}
clean = lambda t: re.sub(r'\s+', ' ', t or '').strip()

def ogg(p, e):
    """CompressedPCData of a SoundNodeWave: the second bulk-data block after the properties (as in voices.py)."""
    r = p.reader(e); r.i32(); p.props(r)
    for i in range(2):
        fl = r.u32(); r.i32(); size = r.u64(); r.u64()
        assert not fl & 1
        data = r.raw(size)
    assert bytes(data[:4]) == b'OggS', e['name']
    return bytes(data)

PAT = re.compile(r'^SNW_VOX_(CH_BB0[1-4]_|CH_MB0[1-4]_|CH_4H_[BRWP]_|BS_\d\d_\d\d|JS_\d\d)')
FFM = {'W': 'FFM_WHITESTEEL', 'R': 'FFM_REDNAPALM', 'B': 'FFM_BLACKTHUNDER', 'P': 'FFM_PALEWIND'}
got = {'en': set(), 'jp': set()}; total = 0
for f in sorted(os.listdir(upk.GAME)):
    m = re.search(r'_LOC_(INT|JPN)\.upk$', f)
    if not m: continue
    lang = 'en' if m.group(1) == 'INT' else 'jp'
    try: p = upk.Package(f)
    except Exception: continue
    for e in p.exports:
        if p.clsname(e) != 'SoundNodeWave' or not PAT.match(e['name']) or e['name'] in got[lang]: continue
        d = ogg(p, e); total += len(d); got[lang].add(e['name'])
        open(os.path.join(OUT, '%s_%s.ogg' % (e['name'][len('SNW_VOX_'):], lang)), 'wb').write(d)
names = sorted(got['en'] & got['jp'])
missing = sorted(got['en'] ^ got['jp'])

out = collections.defaultdict(lambda: dict(combat={}, lines=[]))
for n in names:
    key = n[len('SNW_VOX_'):]
    m = re.match(r'CH_4H_([BRWP])_(.+?)_?(\d+)?$', key)
    if m:
        out[FFM[m.group(1)]]['combat'].setdefault(m.group(2), []).append(key); continue
    m = re.match(r'CH_(BB|MB)0(\d)_(.+?)_?(\d+)?$', key)
    if m:
        who = ('DON_' + ['MAX', 'JACKSON', 'CROWLEY', 'GUNKANYAMA'][int(m.group(2)) - 1]) if m.group(1) == 'BB' else 'MBOSS' + m.group(2)
        out[who]['combat'].setdefault(m.group(3), []).append(key); continue
    m = re.match(r'(BS_\d\d_\d\d)(?:_([A-Z]{5}_\d+))?$', key) or re.match(r'(JS_[\d_]+)()$', key)
    sec, line = m.group(1), m.group(2)
    sub = {}
    for lang, snd in (('en', ''), ('jp', 'jpn')):
        rows = TEXT.get((sec, snd)) or TEXT.get((sec, ''), [])
        if line: rows = [r for r in rows if r[0] == line] or [r for r in TEXT.get((sec, ''), []) if r[0] == line]
        sub[lang] = ' '.join(t for t in (clean(t) for _, t in rows) if t)
    spk = re.match(r'[A-Z]{5}', line or (TEXT.get((sec, ''), [('?????', '')])[0][0]))
    who = SPEAKER.get(spk.group(0) if spk else '', 'other')
    out[who]['lines'].append(dict(clip=key, scene='fight' if sec.startswith('BS') else 'arena', en=sub['en'], jp=sub['jp']))
open('data/bossvoices.js', 'w', encoding='utf-8', newline='\n').write(
    "// Generated by tools/boss_voices.py: the Dons' and mini bosses' voice clips in voice/boss/<clip>_<en|jp>.ogg, with subtitles for spoken lines.\nwindow.BOSS_VOICES = "
    + json.dumps(out, ensure_ascii=False, separators=(',', ':')) + ';\n')
print({k: (sum(len(v) for v in d['combat'].values()), len(d['lines'])) for k, d in out.items()}, len(names), 'clips per language,', total // 1024, 'KB; only in one language:', missing[:10])
