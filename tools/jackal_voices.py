"""Copy every Jackal voice clip (Ogg Vorbis, as the game stores them; nothing is re-encoded) and write data/jackalvoices.js.

Usage (from the site's root folder): jackal_voices.py
LID_MASTERS can point at an unmodded copy of the database, as for items.py.

Clips come from two kinds of package, each in English (LOC_INT) and Japanese (LOC_JPN):
  SN_VOX_CH_JA_<X|Y|Z>_cue_SF        combat voice: Attack, DMG (hurt), Death and Neutral (idle chatter) clips
  SN_VOX_JA_<scene>_cue_SF           spoken lines (01_xx while they work, 03_xx when beaten); the text is in master_text
                                     section JA_<scene>. The game text also has lines for scenes 02 and 04 whose audio
                                     packages are not in the PC game, so those are left out.
They are written to voice/jackal/<clip>_<en|jp>.ogg.
"""
import os, re, json, sqlite3
import upk

def ogg(p, e):
    """CompressedPCData of a SoundNodeWave: the second bulk-data block after the properties (as in voices.py)."""
    r = p.reader(e); r.i32(); p.props(r)
    for i in range(2):
        fl = r.u32(); r.i32(); size = r.u64(); r.u64()
        assert not fl & 1
        data = r.raw(size)
    assert bytes(data[:4]) == b'OggS', e['name']
    return bytes(data)

OUT = os.path.join('voice', 'jackal')
os.makedirs(OUT, exist_ok=True)
DB = os.path.abspath(os.environ.get('LID_MASTERS') or os.path.join(upk.GAME, '..', 'Content', 'masters.db')).replace(os.sep, '/')
c = sqlite3.connect('file:%s?mode=ro' % DB, uri=True)
TEXT = {(s, i, snd): t for s, i, snd, t in c.execute("select sct, id, snd, txt from master_text where lang='int'")}
def subtitle(scene, line):
    """English text of a scene line: master_text section JA_<scene>, id <X|Y|Z>JACK_nnnn (one id carries a stray '_').
    English audio uses the plain text; Japanese audio its own English subtitle (snd 'jpn') when there is one."""
    for i in (line, line + '_'):
        en = TEXT.get(('JA_' + scene, i, ''))
        if en is not None: return dict(en=en, jp=TEXT.get(('JA_' + scene, i, 'jpn')) or en)
    return dict(en='', jp='')

KINDS = [('Attack', 'attack'), ('DMG', 'hurt'), ('Death', 'death'), ('Neutral', 'idle')]
out = {}; total = 0
for lang, loc in (('en', 'INT'), ('jp', 'JPN')):
    for f in sorted(os.listdir(upk.GAME)):
        m = re.fullmatch(r'SN_VOX_(CH_JA_([XYZ])|JA_(\d\d_\d\d))_cue_SF_LOC_%s\.upk' % loc, f)
        if not m: continue
        p = upk.Package(f)
        for e in sorted((e for e in p.exports if p.clsname(e) == 'SoundNodeWave'), key=lambda e: e['name']):
            name = e['name']; d = ogg(p, e); total += len(d)
            key = name[len('SNW_VOX_'):]
            open(os.path.join(OUT, '%s_%s.ogg' % (key, lang)), 'wb').write(d)
            if lang != 'en': continue
            if m.group(2):
                fam = m.group(2)
                kind = next(k for pre, k in KINDS if re.search(r'_%s_\d+$' % pre, name))
                out.setdefault(fam, dict(combat={}, lines=[]))['combat'].setdefault(kind, []).append(key)
            else:
                fam = re.search(r'_([XYZ])JACK_', name).group(1)
                sub = subtitle(m.group(3), re.search(r'[XYZ]JACK_.+$', name).group(0))
                out.setdefault(fam, dict(combat={}, lines=[]))['lines'].append(dict(clip=key, scene=m.group(3), en=sub['en'], jp=sub['jp']))
# every clip must exist in both languages
for fam in out.values():
    for k in [x for v in fam['combat'].values() for x in v] + [l['clip'] for l in fam['lines']]:
        assert os.path.exists(os.path.join(OUT, k + '_jp.ogg')), k
open('data/jackalvoices.js', 'w', encoding='utf-8', newline='\n').write(
    "// Generated by tools/jackal_voices.py: the Jackals' voice clips in voice/jackal/<clip>_<en|jp>.ogg, with subtitles for the spoken lines.\nwindow.JACKAL_VOICES = "
    + json.dumps(out, ensure_ascii=False, separators=(',', ':')) + ';\n')
print({f: (sum(len(v) for v in d['combat'].values()), len(d['lines'])) for f, d in out.items()}, total // 1024, 'KB')
