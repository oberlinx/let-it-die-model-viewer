"""Pack the meshes dumped by extract.py for the page's 3D view.

Per mesh, one <name>.bin: positions (float32 x3), then normals (int8 x3, padded to 4 bytes per vertex),
then UVs (float32 x2), then triangle indices (uint16). data/models3d.js says how many of each.
"""
import os, sys, json
from array import array
SRC, OUT, JS = sys.argv[1], sys.argv[2], sys.argv[3]
os.makedirs(OUT, exist_ok=True)

def load(name, kind, t):
    a = array(t); a.frombytes(open(os.path.join(SRC, '%s.%s.bin' % (name, kind)), 'rb').read()); return a

def pack(info):
    name = info['name']
    # posed vertices from pose.py when present, else the reference (T) pose
    pre = 'pose.' if os.path.exists(os.path.join(SRC, name + '.pose.pos.bin')) else ''
    pos, nrm, uv, idx = load(name, pre + 'pos', 'f'), load(name, pre + 'nrm', 'f'), load(name, 'uv', 'f'), load(name, 'idx', 'I')
    nv = len(pos) // 3
    assert nv < 65536
    n8 = array('b')
    for i in range(nv):
        n8.extend(max(-127, min(127, round(nrm[3 * i + k] * 127))) for k in range(3)); n8.append(0)
    groups = []; tris = array('H')
    for g in info['groups']:
        if 'CutSurface' in g['material']['name']: continue      # hidden caps used when a limb is cut off
        groups.append(dict(start=len(tris), count=g['count'], **({'part': g['part']} if g.get('part') else {})))
        tris.extend(array('H', idx[g['start']:g['start'] + g['count']]))
    with open(os.path.join(OUT, name + '.bin'), 'wb') as f:
        for a in (pos, n8, uv, tris): a.tofile(f)
    return dict(name=name, verts=nv, indices=len(tris), groups=groups)

def pack_pose(info, tag, src_prefix):
    """Alternative pose for the 3D view: <name>.<tag>.bin holds positions and normals only (same layout as the start of <name>.bin)."""
    name = info['name']
    pos, nrm = load(name, src_prefix + 'pos', 'f'), load(name, src_prefix + 'nrm', 'f')
    n8 = array('b')
    for i in range(len(pos) // 3):
        n8.extend(max(-127, min(127, round(nrm[3 * i + k] * 127))) for k in range(3)); n8.append(0)
    with open(os.path.join(OUT, '%s.%s.bin' % (name, tag)), 'wb') as f:
        pos.tofile(f); n8.tofile(f)

models = json.load(open(os.path.join(SRC, 'models.json')))
out = {m['id']: dict(body=pack(m['body']), hair=pack(m['hair']) if m['hair'] else None) for m in models}
for m in models:
    for part in (m['body'], m['hair']):
        if not part: continue
        pack_pose(part, 'tpose', '')                                    # the reference pose straight from the mesh
        if os.path.exists(os.path.join(SRC, part['name'] + '.select.pos.bin')): pack_pose(part, 'select', 'select.')
open(JS, 'w', newline='\n').write('// Generated by tools/pack3d.py: mesh layout for the 3D view (see that script for the .bin format).\nwindow.MODELS3D = '
                                  + json.dumps(out, separators=(',', ':')).replace('},"BODY', '},\n"BODY') + ';\n')
print(len(out), 'models,', sum(os.path.getsize(os.path.join(OUT, f)) for f in os.listdir(OUT) if f.endswith('.bin')) // 1024, 'KB of meshes')
